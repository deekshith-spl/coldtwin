// ── Farmer Report ──────────────────────────────────────────────
function FarmerReport({ farmerId }: { farmerId: string }) {
  const { lots, readings, produceMeta, farmers } = useStore();
  const farmer = farmers.find(f => f.id === farmerId) ?? { id: farmerId, name: farmerId };
  const farmerLots = lots.filter(l => l.farmerId === farmerId);
  const ranked = useMemo(() => rankLots(farmerLots, readings, produceMeta), [farmerLots, readings, produceMeta]);

  return (
    <div className="bg-white p-8 max-w-2xl mx-auto">
      <div className="flex justify-between items-start mb-6 pb-4 border-b-2 border-gray-900">
        <div>
          <div className="text-2xl font-black">LOT STATUS REPORT</div>
          <div className="text-lg font-bold text-cold-700 mt-1">{farmer.name}</div>
          <div className="text-sm text-gray-500">
            {new Date().toLocaleDateString('en-IN', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' })}
          </div>
        </div>
        <div className="text-right text-xs text-gray-400">
          <div>ColdTwin · Estimates only</div>
          <div>For information purposes only</div>
        </div>
      </div>

      {ranked.map(item => (
        <div key={item.lot.id} className="mb-4 p-4 border rounded-lg">
          <div className="flex justify-between">
            <div>
              <div className="font-bold text-lg">{item.lot.id}</div>
              <div className="text-sm text-gray-600 capitalize">{item.lot.produce} · {item.lot.quantityKg} kg · {item.lot.chamberId}</div>
              <div className="text-xs text-gray-400">Arrived: {item.lot.arrivalDate}</div>
            </div>
            <div className="text-right">
              <div className="text-3xl font-black">{item.remainingDays.toFixed(0)}</div>
              <div className="text-xs text-gray-400">days remaining</div>
              <div className="text-xs text-gray-300 mt-0.5">(range {item.lowDays}–{item.highDays})</div>
              <div className="mt-1"><UrgencyChip level={item.urgency} /></div>
            </div>
          </div>
          <div className="mt-2 text-xs text-gray-500 bg-gray-50 p-2 rounded">{item.explanation}</div>
        </div>
      ))}

      {ranked.length === 0 && <div className="text-center text-gray-400 py-8">No lots for this farmer.</div>}

      <div className="mt-6 text-xs text-gray-400 border-t pt-3">
        Estimates only. Visual inspection recommended before sale.
      </div>
    </div>
  );
}

// ── Main Reports Page ─────────────────────────────────────────
export default function Reports() {
  const { lots, readings, produceMeta, chambers, farmers } = useStore();
  const [selectedFarmer, setSelectedFarmer] = useState<string>('');
  const [reportType, setReportType] = useState<'sell-first' | 'farmer'>('sell-first');
  const printRef = useRef<HTMLDivElement>(null);

  const ranked = useMemo(() => rankLots(lots, readings, produceMeta), [lots, readings, produceMeta]);
  const alerts = useMemo(() => chambers.map(chamber => {
    const cr = readings.filter(r => r.chamberId === chamber.id);
    const preds = computeThermalPredictions(chamber, cr);
    return computeFaultAlert(chamber, cr, preds);
  }), [chambers, readings]);

  const handlePrint = () => window.print();

  const exportRankings = () => {
    exportToCSV(ranked.map(r => ({
      rank: r.rank, lotId: r.lot.id, produce: r.lot.produce, chamberId: r.lot.chamberId,
      farmerName: r.lot.farmerName, quantityKg: r.lot.quantityKg,
      remainingDays: r.remainingDays, lowDays: r.lowDays, highDays: r.highDays, urgency: r.urgency,
    })), 'coldtwin_sell_first_list.csv');
  };

  const exportAlerts = () => {
    exportToCSV(alerts.map(a => ({
      chamberId: a.chamberId, riskScore: a.riskScore, level: a.level,
      reason: a.reason, suggestedAction: a.suggestedAction,
    })), 'coldtwin_alerts.csv');
  };

  const uniqueFarmers = [...new Set(lots.map(l => l.farmerId))]
    .map(id => farmers.find(f => f.id === id) ?? { id, name: id });

  return (
    <div className="flex flex-col gap-5">
      <div>
        <h1 className="text-xl font-bold text-gray-900">Reports</h1>
        <p className="text-sm text-gray-500">Print or export data for staff, owners, and farmers.</p>
      </div>

      {/* Controls – hidden during print */}
      <div className="no-print flex flex-wrap gap-3">
        <button
          onClick={() => setReportType('sell-first')}
          className={`btn-${reportType === 'sell-first' ? 'primary' : 'secondary'}`}>
          <FileText size={14} className="inline mr-1" /> Today's Sell-First List
        </button>
        <button
          onClick={() => setReportType('farmer')}
          className={`btn-${reportType === 'farmer' ? 'primary' : 'secondary'}`}>
          <FileText size={14} className="inline mr-1" /> Farmer Report
        </button>
        <span className="w-px bg-gray-200 mx-1" />
        <button onClick={exportRankings} className="btn-secondary flex items-center gap-1.5">
          <Download size={14} /> Export Rankings CSV
        </button>
        <button onClick={exportAlerts} className="btn-secondary flex items-center gap-1.5">
          <Download size={14} /> Export Alerts CSV
        </button>
        <button onClick={handlePrint} className="btn-primary flex items-center gap-1.5">
          <Printer size={14} /> Print / Save PDF
        </button>
      </div>

      {/* Farmer selector */}
      {reportType === 'farmer' && (
        <div className="no-print">
          <label className="text-sm font-medium text-gray-700 block mb-1">Select Farmer</label>
          <select
            value={selectedFarmer}
            onChange={e => setSelectedFarmer(e.target.value)}
            className="border border-gray-300 rounded-lg px-3 py-2 text-sm"
          >
            <option value="">-- Choose a farmer --</option>
            {uniqueFarmers.map(f => <option key={f.id} value={f.id}>{f.name}</option>)}
          </select>
        </div>
      )}

      {/* Report preview */}
      <div ref={printRef} className="border border-gray-200 rounded-xl overflow-hidden">
        {reportType === 'sell-first' ? (
          <SellFirstPrint />
        ) : selectedFarmer ? (
          <FarmerReport farmerId={selectedFarmer} />
        ) : (
          <div className="p-12 text-center text-gray-400">Select a farmer above to preview their report.</div>
        )}
      </div>
    </div>
  );
}
